const norm = s => String(s || '').toLowerCase().replace(/["'״׳]/g, '').trim();

// up to `n` suggestions, best first
export function suggestEmojis(name, n = 3) {
  const s = norm(name);
  const scored = [];
  for (const [keys, emojis] of BANK) {
    let best = 0;
    for (const k of keys) { const kk = norm(k); if (kk && s.includes(kk)) best = Math.max(best, kk.length); }
    if (best) scored.push([best, emojis]);
  }
  scored.sort((a, b) => b[0] - a[0]);
  const out = [];
  for (const [, emojis] of scored) for (const e of emojis) if (!out.includes(e)) out.push(e);
  for (const e of ['✅', '⭐', '🔁', '🎯', '💡']) if (!out.includes(e)) out.push(e);
  return out.slice(0, n);
}

// compare emojis loosely (with/without the variation selector, skin tones)
export const emojiKey = e => String(e || '').replace(/[︎️]|\u{1F3FB}|\u{1F3FC}|\u{1F3FD}|\u{1F3FE}|\u{1F3FF}/gu, '');
export const textHasEmoji = (text, e) => !!e && emojiKey(text).includes(emojiKey(e));
